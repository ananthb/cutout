//! The HTML document every `/manage` route is served from.
//!
//! The Worker answers `/manage` and `/manage/pending` with this shell; the Elm
//! app reads the URL and renders the page. Everything else the browser needs —
//! `/app.js`, `/boot.js`, `/css/*` — is served straight off Cloudflare's asset
//! handler (`[assets]` in `wrangler.toml`) without the Worker running at all.
//!
//! The page carries no copy. Every string the user reads lives in the Elm app,
//! because a second copy here would be the one that goes stale. There is no
//! mount `<div>` either: this is a `Browser.application`, which takes over
//! `<body>` and removes whatever it finds there. That is why the two `<script>`
//! tags are in `<head>` with `defer` rather than at the end of `<body>`, where
//! they would more conventionally go — Elm removes the body's children on init,
//! scripts included.
//!
//! There is deliberately no inline script: initialisation lives in `/boot.js`,
//! which lets the page run under `script-src 'self'` with no nonce.
//!
//! # Subresource Integrity
//!
//! Every stylesheet and both scripts carry an `integrity` hash generated at
//! build time by `build.rs`. An SRI rejection is *silent* — the page still
//! renders, the asset simply never applies — so the ordering that keeps the
//! hashes correct is enforced rather than merely documented:
//!
//! * `scripts/build-worker.sh` builds the frontend before the wasm, so
//!   `build.rs` hashes the `app.js` that will actually be served.
//! * `build.rs` refuses to emit a placeholder for a file it cannot read, so a
//!   crate compiled without the frontend fails loudly rather than producing
//!   hashes that would block the bundle at runtime.

// Generated by build.rs: `CSS_MODULES` and `SCRIPTS`, each
// `[(file, "sha384-…")]` in load order.
include!(concat!(env!("OUT_DIR"), "/asset_sri.rs"));

/// Render the shell.
pub fn html() -> String {
    let stylesheets: String = CSS_MODULES
        .iter()
        .map(|(name, sri)| {
            format!(
                "<link rel=\"stylesheet\" href=\"/css/{name}\" integrity=\"{sri}\" crossorigin=\"anonymous\">\n"
            )
        })
        .collect();

    let scripts: String = SCRIPTS
        .iter()
        .map(|(name, sri)| {
            format!(
                "<script defer src=\"/{name}\" integrity=\"{sri}\" crossorigin=\"anonymous\"></script>\n"
            )
        })
        .collect();

    format!(
        r##"<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Cutout</title>
<meta name="description" content="Transparent email alias proxy: route inbound mail by rule and forward it to email, Telegram or Discord.">
<link rel="icon" type="image/svg+xml" href="/cutout-mark.svg">
<link rel="mask-icon" href="/cutout-mark.svg" color="#e07b39">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="preconnect" href="https://fonts.gstatic.com" crossorigin>
<link href="https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700;800&family=JetBrains+Mono:wght@400;500;600;700&display=swap" rel="stylesheet">
{stylesheets}{scripts}</head>
<body>
</body>
</html>
"##,
        stylesheets = stylesheets,
        scripts = scripts
    )
}
